/// Johnson SB distribution on `(0, 1)` with shift `a` and shape `b > 0`.
///
/// `a + b ln(X / (1 − X))` is standard normal. Probabilities and quantiles
/// reduce to the standard normal law. The mean and variance are computed by
/// quadrature, within the [work limits](crate#work-limits).
///
/// # References
///
/// N. L. Johnson, "Systems of frequency curves generated by methods of
/// translation", *Biometrika* 36(1–2), 1949, 149–176.
///
/// ```
/// use scioxide_random::{
///     Cdf, Distribution, JohnsonSB, Mean, Quantile, SeedableRng, SplitMix64,
/// };
/// let law = JohnsonSB::<f64>::new(0.0, 1.0)?;
/// assert!((law.cdf(0.5)? - 0.5).abs() < 1e-15);
/// let x = law.quantile(0.8)?;
/// assert!((law.cdf(x)? - 0.8).abs() < 1e-14);
/// assert!((law.mean()? - 0.5).abs() < 1e-8);
/// let mut rng = SplitMix64::from_seed(21);
/// let x = law.sample(&mut rng)?;
/// assert!(x > 0.0 && x < 1.0);
/// # Ok::<(), scioxide_core::SciOxideError>(())
/// ```
#[derive(Debug, Clone)]
pub struct JohnsonSB<S: RealScalar> {
    options: LawOptions<S>,
    a: S,
    b: S,
    normal: super::Normal<S>,
}
impl<S: RealScalar> JohnsonSB<S> {
    /// Creates a Johnson SB distribution with shift `a` and shape `b`.
    ///
    /// It uses the default [`LawOptions`](crate::LawOptions); [`Self::with_options`] sets the
    /// tolerance and work limits.
    ///
    /// # Errors
    ///
    /// - `NonFinite` if `a` or `b` is NaN or infinite.
    /// - `DomainError` if `b ≤ 0`.
    pub fn new(a: S, b: S) -> Result<Self, SciOxideError> {
        Self::with_options(a, b, LawOptions::default())
    }

    /// Creates the law of [`Self::new`] with the tolerance and work limits of `options`.
    ///
    /// # Errors
    ///
    /// - The errors of [`Self::new`].
    /// - `InvalidInput` if `options` is invalid; see [`LawOptions`](crate::LawOptions).
    pub fn with_options(a: S, b: S, options: LawOptions<S>) -> Result<Self, SciOxideError> {
        options.validate()?;
        argument(a, "a")?;
        positive(b, scioxide_core::argument!("b"))?;
        Ok(Self {
            options,
            a,
            b,
            normal: super::Normal::standard(),
        })
    }

    // Johnson S_B is a normal law pushed through the logistic map, so every
    // tail and quantile reduces to the standard normal at a + b logit(x).
    fn z(&self, x: S) -> Result<S, SciOxideError> {
        Ok(self.b.mul_add(scioxide_core::logit(x)?, self.a))
    }
}
impl<S: RealScalar> Formula<S> for JohnsonSB<S> {
    fn tolerance(&self) -> scioxide_core::Tolerance<S> {
        self.options.tolerance()
    }

    fn work_budget(&self) -> scioxide_core::Budget {
        self.options.work_budget()
    }
    fn byte_limit(&self) -> usize {
        self.options.max_bytes()
    }

    fn bounds(&self) -> (Option<S>, Option<S>) {
        unit()
    }
    fn density_log(&self, x: S) -> Result<S, SciOxideError> {
        if x <= S::ZERO || x >= S::ONE {
            return Ok(S::NEG_INFINITY);
        }
        Ok(self.b.ln() + self.normal.log_pdf(self.z(x)?)? - x.ln() - (-x).ln_1p())
    }
    fn tail_with_work(&self, x: S, upper: bool, _left: &mut usize) -> Result<S, SciOxideError> {
        if upper {
            if x <= S::ZERO {
                Ok(S::ZERO)
            } else if x >= S::ONE {
                Ok(S::NEG_INFINITY)
            } else {
                self.normal.log_sf(self.z(x)?)
            }
        } else {
            if x <= S::ZERO {
                Ok(S::NEG_INFINITY)
            } else if x >= S::ONE {
                Ok(S::ZERO)
            } else {
                self.normal.log_cdf(self.z(x)?)
            }
        }
    }
    fn inverse(&self, p: S) -> Result<S, SciOxideError> {
        if p == S::ZERO {
            return Ok(S::ZERO);
        }
        if p == S::ONE {
            return Ok(S::ONE);
        }
        scioxide_core::sigmoid((self.normal.quantile(p)? - self.a) / self.b)
    }
    fn inverse_upper(&self, p: S) -> Result<S, SciOxideError> {
        if p == S::ZERO {
            return Ok(S::ONE);
        }
        if p == S::ONE {
            return Ok(S::ZERO);
        }
        scioxide_core::sigmoid((self.normal.isf(p)? - self.a) / self.b)
    }

    fn draw_with_remaining<R: Rng<S>>(
        &self,
        rng: &mut R,
        __left: &mut usize,
    ) -> Result<S, SciOxideError> {
        scioxide_core::sigmoid((self.normal.sample(rng)? - self.a) / self.b)
    }
}
formula_law!(JohnsonSB);
impl<S: RealScalar> Mean<S> for JohnsonSB<S> {
    fn mean(&self) -> Result<S, SciOxideError> {
        self.mean_work(&mut self.options.work_budget().get())
    }

    fn mean_scoped(
        &self,
        context: &mut scioxide_core::SolveContext<'_, '_>,
    ) -> Result<S, SciOxideError> {
        crate::law::with_work(context, self.options.work_budget(), |left| {
            self.mean_work(left)
        })
    }
}
impl<S: RealScalar> JohnsonSB<S> {
    fn mean_work(&self, left: &mut usize) -> Result<S, SciOxideError> {
        let options = self.options;
        quantile_mean(self, options, left)
    }
}

impl<S: RealScalar> Variance<S> for JohnsonSB<S> {
    fn variance(&self) -> Result<S, SciOxideError> {
        self.variance_work(&mut self.options.work_budget().get())
    }

    fn variance_scoped(
        &self,
        context: &mut scioxide_core::SolveContext<'_, '_>,
    ) -> Result<S, SciOxideError> {
        crate::law::with_work(context, self.options.work_budget(), |left| {
            self.variance_work(left)
        })
    }
}
impl<S: RealScalar> JohnsonSB<S> {
    fn variance_work(&self, left: &mut usize) -> Result<S, SciOxideError> {
        let options = self.options;
        quantile_variance(self, options, left)
    }
}

/// Johnson SU distribution on the real line with shift `a` and shape `b > 0`.
///
/// `X = sinh((Z − a)/b)` for a standard normal `Z`, so `a + b asinh(X)` is
/// standard normal.
///
/// # References
///
/// N. L. Johnson, "Systems of frequency curves generated by methods of
/// translation", *Biometrika* 36(1–2), 1949, 149–176.
///
/// ```
/// use scioxide_random::{
///     Cdf, Distribution, JohnsonSU, Mean, Quantile, SeedableRng, SplitMix64,
/// };
/// let law = JohnsonSU::<f64>::new(1.0, 2.0)?;
/// let x = law.quantile(0.7)?;
/// assert!((law.cdf(x)? - 0.7).abs() < 1e-14);
/// assert!((law.mean()? + 0.125_f64.exp() * 0.5_f64.sinh()).abs() < 1e-14);
/// let mut rng = SplitMix64::from_seed(22);
/// assert!(law.sample(&mut rng)?.is_finite());
/// # Ok::<(), scioxide_core::SciOxideError>(())
/// ```
#[derive(Debug, Clone, Copy)]
pub struct JohnsonSU<S: RealScalar> {
    a: S,
    b: S,
}
impl<S: RealScalar> JohnsonSU<S> {
    /// Creates a Johnson SU distribution with shift `a` and shape `b`.
    ///
    /// # Errors
    ///
    /// - `NonFinite` if `a` or `b` is NaN or infinite.
    /// - `DomainError` if `b ≤ 0`.
    pub fn new(a: S, b: S) -> Result<Self, SciOxideError> {
        crate::law::argument(a, "a")?;
        positive(b, scioxide_core::argument!("b"))?;
        Ok(Self { a, b })
    }
    fn normal_point(&self, x: S) -> S {
        self.b.mul_add(x.asinh(), self.a)
    }
}
impl<S: RealScalar> Formula<S> for JohnsonSU<S> {
    fn bounds(&self) -> (Option<S>, Option<S>) {
        (None, None)
    }
    fn density_log(&self, x: S) -> Result<S, SciOxideError> {
        Ok(self.b.ln() - x.hypot(S::ONE).ln() + normal_log_density(self.normal_point(x)))
    }
    fn tail_with_work(&self, x: S, upper: bool, _left: &mut usize) -> Result<S, SciOxideError> {
        if upper {
            scioxide_special::normal_log_sf(self.normal_point(x))
        } else {
            scioxide_special::normal_log_cdf(self.normal_point(x))
        }
    }
    fn inverse(&self, p: S) -> Result<S, SciOxideError> {
        if p == S::ZERO {
            return Ok(S::NEG_INFINITY);
        }
        if p == S::ONE {
            return Ok(S::INFINITY);
        }
        finite(((scioxide_special::normal_quantile(p)? - self.a) / self.b).sinh())
    }
    fn inverse_upper(&self, p: S) -> Result<S, SciOxideError> {
        if p == S::ZERO {
            return Ok(S::INFINITY);
        }
        if p == S::ONE {
            return Ok(S::NEG_INFINITY);
        }
        finite(((-scioxide_special::normal_quantile(p)? - self.a) / self.b).sinh())
    }

    fn draw_with_remaining<R: Rng<S>>(
        &self,
        rng: &mut R,
        __left: &mut usize,
    ) -> Result<S, SciOxideError> {
        let z = super::Normal::standard().sample(rng)?;
        finite(((z - self.a) / self.b).sinh())
    }
}
formula_law!(JohnsonSU);
impl<S: RealScalar> Mean<S> for JohnsonSU<S> {
    fn mean(&self) -> Result<S, SciOxideError> {
        if self.a == S::ZERO {
            return Ok(S::ZERO);
        }
        let a = self.a.into_f64();
        let b = self.b.into_f64();
        let u = a.abs() / b;
        let log_sinh = if u < f64::SQRT_EPSILON {
            a.abs().ln() - b.ln()
        } else {
            u + crate::law::log1mexp(-2.0 * u)? - core::f64::consts::LN_2
        };
        let magnitude = crate::law::positive_draw::<S>(0.5 / b / b + log_sinh)?;
        Ok(if a < 0.0 { magnitude } else { -magnitude })
    }
}
impl<S: RealScalar> Variance<S> for JohnsonSU<S> {
    fn variance(&self) -> Result<S, SciOxideError> {
        let inverse = self.b.into_f64().recip();
        let v = inverse * inverse;
        let u = self.a.into_f64() * inverse;
        // Var = expm1(v) * (exp(v)*cosh(2u) + 1)/2. Work in logs
        // so overflowing intermediate hyperbolic functions cannot lose range.
        let log_v = -2.0 * self.b.into_f64().ln();
        let log_expm1 = if v < f64::EPSILON {
            log_v
        } else {
            crate::law::log_expm1(v)?
        };
        let twice_u = 2.0 * u.abs();
        let log_cosh = twice_u + (-2.0 * twice_u).exp().ln_1p() - core::f64::consts::LN_2;
        super::moment_math::variance(
            log_expm1 + scioxide_core::softplus(v + log_cosh)? - core::f64::consts::LN_2,
        )
    }
}
