//! Niederreiter base-2 generator matrices (Bratley, Fox and Niederreiter, "Implementation and
//! tests of low-discrepancy sequences", ACM TOMACS 2(3), 1992, §2.3 and §3.3).
//!
//! Dimension `j` uses the `j`-th monic irreducible polynomial over GF(2), ordered by degree and,
//! within one degree, by the integer whose bit `k` is the coefficient of `xᵏ`: `x`, `x + 1`,
//! `x² + x + 1`, `x³ + x + 1`, `x³ + x² + 1`, …. The Laurent-series coefficients that the
//! construction leaves free are set to 1. Polynomial powers are represented in u128: degrees
//! through 66 suffice for 64 output digits and the supported degree-five polynomials.
use super::plan::invalid;
use alloc::vec::Vec;
use scioxide_core::SciOxideError;

// The first twelve monic irreducible polynomials over GF(2) in increasing
// degree order (bit k is the coefficient of x^k): x, x+1, x^2+x+1, ... .
// Distinct irreducibles per dimension are what give the net its t-value.
const POLYNOMIALS: [u128; 12] = [2, 3, 7, 11, 13, 19, 25, 31, 37, 41, 47, 55];

pub(super) fn directions(dimensions: usize) -> Result<Vec<[u64; 64]>, SciOxideError> {
    if !(1..=12).contains(&dimensions) {
        return Err(invalid(
            scioxide_core::argument!("dimensions"),
            "Niederreiter base-2 supports 1 through 12 dimensions",
        ));
    }
    let mut result = scioxide_core::backend::try_with_capacity(
        dimensions,
        scioxide_core::quantity!("niederreiter_directions"),
    )?;
    result.extend(POLYNOMIALS[..dimensions].iter().copied().map(columns));
    Ok(result)
}
// Carry-less multiplication in GF(2)[x]; products of the small polynomials
// used here stay within u128 for all 64 generated digits.
fn multiply(mut left: u128, mut right: u128) -> u128 {
    let mut product = 0;
    while right != 0 {
        if right & 1 != 0 {
            product ^= left;
        }
        right >>= 1;
        left <<= 1;
    }
    product
}
fn columns(polynomial: u128) -> [u64; 64] {
    let degree = (127 - polynomial.leading_zeros()) as usize;
    let mut power = 1;
    let mut power_degree = 0;
    let mut v = [0_u8; 130];
    let mut columns = [0_u64; 64];
    // Niederreiter's (1988) base-2 construction as in Bratley-Fox-Niederreiter:
    // each block of `degree` digits uses the next power p^k of the dimension's
    // polynomial, and v holds the Laurent-series coefficients of x^offset / p^k,
    // generated by the linear recurrence defined by p^k. Column r of the
    // generator matrix takes bit v[r + offset].
    for digit in 0..64 {
        let offset = digit % degree;
        if offset == 0 {
            let previous_degree = power_degree;
            power = multiply(power, polynomial);
            power_degree += degree;
            v.fill(0);
            v[previous_degree..power_degree].fill(1);
            for r in 0..v.len() - power_degree {
                v[r + power_degree] = (0..power_degree)
                    .fold(0, |value, k| value ^ (((power >> k) & 1) as u8 & v[r + k]));
            }
        }
        columns
            .iter_mut()
            .enumerate()
            .for_each(|(r, column)| *column |= u64::from(v[r + offset]) << (63 - digit));
    }
    columns
}
